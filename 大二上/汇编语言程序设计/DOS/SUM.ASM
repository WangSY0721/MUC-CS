DATAS SEGMENT
    ;此处输入数据段代码
    S DW 0
    N DB 0
    H DB 0
    HUN DB 100
    TEN DB 10
    MAX DW 500
    STR1 DB 'S=','$'
    STR2 DB 10,13,'N=','$'
DATAS ENDS

STACKS SEGMENT
    ;此处输入堆栈段代码
STACKS ENDS

CODES SEGMENT
    ASSUME CS:CODES,DS:DATAS,SS:STACKS
START:
    MOV AX,DATAS
    MOV DS,AX
    ;此处输入代码段代码
	MOV CX,S
	MOV BL,N
	MOV BH,0
	
AGAIN:
	CMP CX,MAX
	JG EXIT
	INC BX
	ADD CX,BX
	JMP AGAIN
	
EXIT:
;输出S=528
	MOV AH,9
	MOV DX,OFFSET STR1
	INT 21H
	
	MOV AX,CX
	DIV HUN
	MOV CX,AX
	;ADD CX,3030H
	
	MOV AH,2
	ADD CL,30H
	MOV DL,CL
	INT 21H;输出百位
	
	MOV CL,CH
	MOV CH,0
	MOV AX,CX
	DIV TEN
	MOV CX,AX
	ADD CX,3030H
	 
	MOV AH,2
	MOV DL,CL
	INT 21H;输出十位
	MOV DL,CH
	INT 21H;输出个位
;输出N=32	
	MOV AH,9
	MOV DX,OFFSET STR2
	INT 21H
	
	MOV AL,BL
	MOV AH,BH
	DIV TEN
	MOV BX,AX
	ADD BX,3030H
	
	MOV AH,2
	MOV DL,BL
	INT 21H
	MOV DL,BH
	INT 21H
	
    MOV AH,4CH
    INT 21H
CODES ENDS
    END START

