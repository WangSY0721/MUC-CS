s = [9, 7, 8, 3, 2, 1, 55, 6]

element_count = len(s)
max_value = max(s)
min_value = min(s)
sum_of_elements = sum(s)
average_value = sum_of_elements / element_count

print("元素个数：", element_count)
print("最大值：", max_value)
print("最小值：", min_value)
print("和：", sum_of_elements)
print("平均值：", average_value)
